import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const source = resolve(root, "content/v2/manifest.authoring.json");
const output = resolve(root, "src/generated/content-catalog.ts");
const checkOnly = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(source, "utf8"));
const runtime = manifest.lifecycle === "runtime" ? manifest.runtime : null;
if (!runtime) throw new Error("Gate 8 client catalog requires the approved runtime manifest");

const pickItems = runtime.items.map(({ id, name, value, kind, family, icon_key, rarity, tier_index, level_requirement, stackable, tradable, colour, stats, equip_skill }) => ({
  id, name, value, kind, family, icon_key, rarity, tier_index, level_requirement, stackable, tradable, colour, stats, ...(equip_skill ? { equip_skill } : {}),
}));
const pickNodes = runtime.nodes.map(({ kind, name, skill, item_id, tier_index, level_requirement, visual }) => ({ kind, name, skill, item_id, tier_index, level_requirement, visual }));
const pickMonsters = runtime.monsters.map(({ kind, name, hp, attack, defense, tier_index, level_requirement, visual_key }) => ({ kind, name, hp, attack, defense, tier_index, level_requirement, visual_key }));
const pickQuests = runtime.quests.map(({ id, name, description, kind, target_id, count, gold, xp_skill, xp, item_reward, tier_index, level_requirement }) => ({ id, name, description, kind, target_id, count, gold, xp_skill, xp, item_reward, tier_index, level_requirement }));

const generated = `/* eslint-disable */\n/* GENERATED by scripts/gate8/build-content-catalog.mjs. Do not edit. */\n\n` +
  `export const V2_CONTENT_ITEMS = ${JSON.stringify(pickItems, null, 2)} as const;\n` +
  `export const V2_CONTENT_NODES = ${JSON.stringify(pickNodes, null, 2)} as const;\n` +
  `export const V2_CONTENT_MONSTERS = ${JSON.stringify(pickMonsters, null, 2)} as const;\n` +
  `export const V2_CONTENT_QUESTS = ${JSON.stringify(pickQuests, null, 2)} as const;\n\n` +
  `export const V2_ITEM_BY_ID = Object.fromEntries(V2_CONTENT_ITEMS.map((entry) => [entry.id, entry])) as Record<(typeof V2_CONTENT_ITEMS)[number]["id"], (typeof V2_CONTENT_ITEMS)[number]>;\n` +
  `export const V2_NODE_BY_KIND = Object.fromEntries(V2_CONTENT_NODES.map((entry) => [entry.kind, entry])) as Record<(typeof V2_CONTENT_NODES)[number]["kind"], (typeof V2_CONTENT_NODES)[number]>;\n` +
  `export const V2_MONSTER_BY_KIND = Object.fromEntries(V2_CONTENT_MONSTERS.map((entry) => [entry.kind, entry])) as Record<(typeof V2_CONTENT_MONSTERS)[number]["kind"], (typeof V2_CONTENT_MONSTERS)[number]>;\n`;

if (checkOnly) {
  if (await readFile(output, "utf8").catch(() => "") !== generated) throw new Error("Gate 8 client content catalog drifted");
  console.log(`Verified v2 client catalog (${pickItems.length} items, ${pickNodes.length} nodes, ${pickMonsters.length} monsters, ${pickQuests.length} quests)`);
} else {
  await writeFile(output, generated);
  console.log(`Wrote ${output.slice(root.length + 1)}`);
}
