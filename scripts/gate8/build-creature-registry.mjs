import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const source = resolve(root, "content/v2/sprite-metadata.json");
const output = resolve(root, "src/generated/creature-sprites.ts");
const checkOnly = process.argv.includes("--check");

const metadata = JSON.parse(await readFile(source, "utf8"));
const sprites = metadata.sprites.map((sprite) => ({
  ...sprite,
  asset_path: `/${sprite.asset_path}`,
}));

const generated = `/* eslint-disable */\n/* GENERATED by scripts/gate8/build-creature-registry.mjs. Do not edit. */\n\n` +
  `export const CREATURE_SPRITES = ${JSON.stringify(sprites, null, 2)} as const;\n` +
  `export type CreatureSpriteKind = (typeof CREATURE_SPRITES)[number]["kind"];\n` +
  `export const CREATURE_SPRITE_BY_KIND = Object.fromEntries(CREATURE_SPRITES.map((sprite) => [sprite.kind, sprite])) as Record<CreatureSpriteKind, (typeof CREATURE_SPRITES)[number]>;\n` +
  `const images = new Map<CreatureSpriteKind, HTMLImageElement>();\n` +
  `let preload: Promise<void> | null = null;\n` +
  `export function preloadCreatureSprites(): Promise<void> {\n` +
  `  if (preload) return preload;\n` +
  `  if (typeof Image === "undefined") return Promise.resolve();\n` +
  `  preload = Promise.all(CREATURE_SPRITES.map((sprite) => new Promise<void>((resolve) => {\n` +
  `    const image = new Image();\n` +
  `    image.onload = () => { images.set(sprite.kind, image); resolve(); };\n` +
  `    image.onerror = () => resolve();\n` +
  `    image.src = sprite.asset_path;\n` +
  `  }))).then(() => undefined);\n` +
  `  return preload;\n` +
  `}\n` +
  `export function creatureSpriteImage(kind: string): HTMLImageElement | null {\n` +
  `  return images.get(kind as CreatureSpriteKind) ?? null;\n` +
  `}\n` +
  `export function creatureSprite(kind: string) {\n` +
  `  return CREATURE_SPRITE_BY_KIND[kind as CreatureSpriteKind] ?? null;\n` +
  `}\n` +
  `export function drawCreatureSprite(ctx: CanvasRenderingContext2D, kind: string, x: number, y: number, bob = 0, hitFlash = false, scale = 0.42): boolean {\n` +
  `  const sprite = creatureSprite(kind);\n` +
  `  const image = creatureSpriteImage(kind);\n` +
  `  if (!sprite || !image) return false;\n` +
  `  const renderedScale = scale * sprite.render_scale;\n` +
  `  const left = Math.round(x - sprite.pivot.x * renderedScale);\n` +
  `  const top = Math.round(y + bob - sprite.pivot.y * renderedScale);\n` +
  `  const width = Math.round(sprite.canvas.width * renderedScale);\n` +
  `  const height = Math.round(sprite.canvas.height * renderedScale);\n` +
  `  const smooth = ctx.imageSmoothingEnabled;\n` +
  `  ctx.imageSmoothingEnabled = false;\n` +
  `  ctx.drawImage(image, left, top, width, height);\n` +
  `  if (hitFlash) {\n` +
  `    ctx.save();\n` +
  `    ctx.globalCompositeOperation = "source-atop";\n` +
  `    ctx.globalAlpha = 0.62;\n` +
  `    ctx.fillStyle = "#ffffff";\n` +
  `    ctx.fillRect(left, top, width, height);\n` +
  `    ctx.restore();\n` +
  `  }\n` +
  `  ctx.imageSmoothingEnabled = smooth;\n` +
  `  return true;\n` +
  `}\n` +
  `export function creaturePointerHit(kind: string, x: number, y: number, pointerX: number, pointerY: number, scale = 0.42): boolean | null {\n` +
  `  const sprite = CREATURE_SPRITE_BY_KIND[kind as CreatureSpriteKind];\n` +
  `  if (!sprite) return null;\n` +
  `  const left = x + (sprite.click_bounds.left - sprite.pivot.x) * scale;\n` +
  `  const right = x + (sprite.click_bounds.right - sprite.pivot.x) * scale;\n` +
  `  const top = y + (sprite.click_bounds.top - sprite.pivot.y) * scale;\n` +
  `  const bottom = y + (sprite.click_bounds.bottom - sprite.pivot.y) * scale;\n` +
  `  return pointerX >= left && pointerX <= right && pointerY >= top && pointerY <= bottom;\n` +
  `}\n`;

if (checkOnly) {
  if (await readFile(output, "utf8").catch(() => "") !== generated) throw new Error("Creature sprite registry drifted");
  console.log(`Verified ${sprites.length} creature sprite records`);
} else {
  await writeFile(output, generated);
  console.log(`Wrote ${output.slice(root.length + 1)}`);
}
