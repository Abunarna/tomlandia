import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const foundationPath = resolve(root, "supabase/gate6/runtime-foundation.sql");
const actionsPath = resolve(root, "supabase/gate6/runtime-actions.sql");
const manifestPath = resolve(root, "artifacts/v2/supabase/generated/content-manifest.sql");
const progressionPath = resolve(root, "docs/overhaul/gate-3/progression.proposed.csv");
const outputPath = resolve(root, "supabase/migrations/20260824090000_gate6_inactive_server_content.sql");
const checkOnly = process.argv.includes("--check");

function stripTransaction(sql) {
  const withoutBegin = sql.replace(/^BEGIN;\s*/m, "");
  const withoutCommit = withoutBegin.replace(/\s*COMMIT;\s*$/m, "\n");
  if (withoutBegin === sql || withoutCommit === withoutBegin) {
    throw new Error("Gate 5 manifest must contain one outer BEGIN/COMMIT pair");
  }
  if (/^\s*(BEGIN|COMMIT);\s*$/m.test(withoutCommit)) {
    throw new Error("Unexpected nested transaction in Gate 5 manifest");
  }
  return withoutCommit.trim();
}

function progressionInsert(csv) {
  const [headerLine, ...rows] = csv.trim().split(/\r?\n/);
  const headers = headerLine.split(",");
  const required = ["level", "xp_to_next", "cumulative_xp"];
  for (const field of required) {
    if (!headers.includes(field)) throw new Error(`Missing progression field: ${field}`);
  }
  const index = Object.fromEntries(headers.map((name, position) => [name, position]));
  if (rows.length !== 150) throw new Error(`Expected 150 progression rows, found ${rows.length}`);

  const values = rows.map((row, rowIndex) => {
    const columns = row.split(",");
    const level = Number(columns[index.level]);
    const xpToNext = columns[index.xp_to_next] === "" ? "NULL" : Number(columns[index.xp_to_next]);
    const cumulative = Number(columns[index.cumulative_xp]);
    if (level !== rowIndex + 1 || !Number.isSafeInteger(cumulative)) {
      throw new Error(`Invalid progression row ${rowIndex + 1}`);
    }
    if (xpToNext !== "NULL" && !Number.isSafeInteger(xpToNext)) {
      throw new Error(`Invalid xp_to_next at level ${level}`);
    }
    return `  ('v2', ${level}, ${xpToNext}, ${cumulative})`;
  });

  return [
    "INSERT INTO public.game_content_progression_levels",
    "  (content_version, level, xp_to_next, cumulative_xp)",
    "VALUES",
    `${values.join(",\n")};`,
  ].join("\n");
}

const [foundation, actions, manifest, progression] = await Promise.all([
  readFile(foundationPath, "utf8"),
  readFile(actionsPath, "utf8"),
  readFile(manifestPath, "utf8"),
  readFile(progressionPath, "utf8"),
]);

const manifestBody = stripTransaction(manifest);
const gate5Hash = createHash("sha256").update(manifest).digest("hex");
const generated = [
  "-- Gate 6: additive inactive server content.",
  "--",
  "-- GENERATED by scripts/gate6/build-migration.mjs. Do not edit this file",
  "-- directly; edit the Gate 6 SQL sources or approved progression source.",
  `-- Embedded Gate 5 SQL artifact sha256: ${gate5Hash}`,
  "-- This migration stages v2 but never activates it.",
  "",
  "BEGIN;",
  "",
  foundation.trim(),
  "",
  "-- Embed the hash-verified Gate 5 manifest as migration-owned staged data.",
  manifestBody,
  "",
  "-- Bind the approved Gate 3 level curve to the staged content version.",
  progressionInsert(progression),
  "",
  actions.trim(),
  "",
  "DO $$",
  "BEGIN",
  "  IF (SELECT status FROM public.game_content_versions WHERE content_version = 'v2') <> 'staged' THEN",
  "    RAISE EXCEPTION 'Gate 6 must leave v2 staged';",
  "  END IF;",
  "  IF EXISTS (SELECT 1 FROM public.game_content_control) THEN",
  "    RAISE EXCEPTION 'Gate 6 must not create an activation control row';",
  "  END IF;",
  "  IF public.game_active_content_version() <> 'v1' THEN",
  "    RAISE EXCEPTION 'Gate 6 runtime must default to v1';",
  "  END IF;",
  "  IF (SELECT count(*) FROM public.game_content_progression_levels WHERE content_version = 'v2') <> 150 THEN",
  "    RAISE EXCEPTION 'Gate 6 progression seed is incomplete';",
  "  END IF;",
  "END",
  "$$;",
  "",
  "COMMIT;",
  "",
].join("\n");

if (checkOnly) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== generated) {
    throw new Error("Gate 6 migration drifted; run node scripts/gate6/build-migration.mjs");
  }
  console.log("Gate 6 migration is deterministic and current.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath.slice(root.length + 1)}`);
}
