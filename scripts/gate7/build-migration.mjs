import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { auditLegacyV1World } from "./legacy-v1-world.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const runtimePath = resolve(root, "supabase/gate7/world-runtime.sql");
const manifestPath = resolve(root, "content/v2/world-spawn-manifest.json");
const reachabilityPath = resolve(root, "docs/overhaul/gate-7/reachability-report.json");
const outputPath = resolve(root, "supabase/migrations/20260824100000_gate7_versioned_world.sql");
const checkOnly = process.argv.includes("--check");

const [runtime, manifestText, reachabilityText, legacyV1] = await Promise.all([
  readFile(runtimePath, "utf8"),
  readFile(manifestPath, "utf8"),
  readFile(reachabilityPath, "utf8"),
  auditLegacyV1World(root),
]);
const manifest = JSON.parse(manifestText);
const reachability = JSON.parse(reachabilityText);

if (reachability.spawn_hash !== manifest.spawn_hash) throw new Error("Gate 7 spawn/reachability hash mismatch");
if (reachability.summary.spawn_issues || reachability.summary.unreachable_clusters || reachability.summary.failed_tiers) {
  throw new Error("Gate 7 cannot generate SQL from failing reachability evidence");
}

const sqlText = (value) => `'${String(value).replaceAll("'", "''")}'`;
const sqlJson = (value) => `${sqlText(JSON.stringify(value))}::jsonb`;
const sqlBool = (value) => value ? "true" : "false";
const sqlNumber = (value) => {
  if (!Number.isFinite(value)) throw new Error(`Cannot emit non-finite SQL number: ${value}`);
  return String(value);
};
const valuesBlock = (rows) => `VALUES\n${rows.map((row) => `  (${row.join(", ")})`).join(",\n")}`;

const contentRows = manifest.spawns.map((spawn) => [
  sqlText(spawn.spawn_id),
  sqlText(manifest.content_version),
  sqlText(manifest.spawn_set_version),
  sqlText(spawn.entity_type),
  sqlText(spawn.kind),
  sqlNumber(spawn.ordinal),
  sqlBool(spawn.active),
  sqlText(spawn.biome),
  sqlText(spawn.subzone),
  sqlNumber(spawn.x),
  sqlNumber(spawn.y),
]);
const nodeRows = manifest.spawns.filter((spawn) => spawn.entity_type === "node").map((spawn) => [
  sqlText(spawn.spawn_id),
  sqlText(manifest.content_version),
  sqlText(manifest.spawn_set_version),
  sqlText(spawn.kind),
  sqlText(spawn.cell),
  sqlText(spawn.biome),
  sqlText(spawn.subzone),
  sqlNumber(spawn.x),
  sqlNumber(spawn.y),
  sqlNumber(spawn.charges),
  sqlNumber(spawn.max_charges),
  sqlNumber(spawn.gather_s),
  sqlNumber(spawn.respawn_s),
]);
const monsterRows = manifest.spawns.filter((spawn) => spawn.entity_type === "monster").map((spawn) => [
  sqlText(spawn.spawn_id),
  sqlText(manifest.content_version),
  sqlText(manifest.spawn_set_version),
  sqlText(spawn.kind),
  sqlText(spawn.cell),
  sqlText(spawn.biome),
  sqlText(spawn.subzone),
  sqlNumber(spawn.x),
  sqlNumber(spawn.y),
  sqlNumber(spawn.hp),
  sqlNumber(spawn.max_hp),
  sqlNumber(spawn.respawn_s),
]);

const sourceHashes = {
  runtime: createHash("sha256").update(runtime).digest("hex"),
  manifest: createHash("sha256").update(manifestText).digest("hex"),
  reachability: createHash("sha256").update(reachabilityText).digest("hex"),
};

const generated = [
  "-- Gate 7: deterministic, versioned and reversible world state.",
  "--",
  "-- GENERATED by scripts/gate7/build-migration.mjs. Do not edit this file directly.",
  `-- World runtime source sha256: ${sourceHashes.runtime}`,
  `-- World manifest artifact sha256: ${sourceHashes.manifest}`,
  `-- Reachability artifact sha256: ${sourceHashes.reachability}`,
  `-- Stable spawn payload sha256: ${manifest.spawn_hash}`,
  `-- Legacy integer v1 DB audit: ${legacyV1.node_count} nodes, ${legacyV1.monster_count} monsters, ${legacyV1.tungsten_node_count} Tungsten`,
  `-- Legacy reset migration sha256: ${legacyV1.reset_migration_hash}`,
  `-- Legacy southern extension sha256: ${legacyV1.southern_extension_migration_hash}`,
  "-- This migration stages UUID v2 rows and never activates them.",
  "",
  "BEGIN;",
  "",
  "DO $gate7_staged_guard$",
  "BEGIN",
  `  IF (SELECT status FROM public.game_content_versions WHERE content_version = ${sqlText(manifest.content_version)}) <> 'staged' THEN`,
  "    RAISE EXCEPTION 'Gate 7 requires inactive staged v2 content';",
  "  END IF;",
  "  IF EXISTS (SELECT 1 FROM public.game_content_control) THEN",
  "    RAISE EXCEPTION 'Gate 7 refuses to seed while an activation control row exists';",
  "  END IF;",
  "END",
  "$gate7_staged_guard$;",
  "",
  runtime.trim(),
  "",
  "INSERT INTO public.game_world_spawn_sets",
  "  (content_version, spawn_set_version, source_content_manifest_hash, spawn_hash, model_version,",
  "   cluster_probability, world_width, world_height, movement_speed, path_cell_size,",
  "   winter_geometry, reachability_summary)",
  `VALUES (${sqlText(manifest.content_version)}, ${sqlText(manifest.spawn_set_version)}, ` +
    `${sqlText(manifest.source_content_manifest_hash)}, ${sqlText(manifest.spawn_hash)}, ` +
    `${sqlText(manifest.model_version)}, ${sqlNumber(manifest.cluster_selection.clustered_probability)}, ` +
    `${sqlNumber(manifest.world.width)}, ${sqlNumber(manifest.world.height)}, ` +
    `${sqlNumber(manifest.world.movement_speed_world_units_per_second)}, ${sqlNumber(manifest.world.path_cell_size)}, ` +
    `${sqlJson(manifest.winter_geometry)}, ${sqlJson(reachability.summary)})`,
  "ON CONFLICT (content_version, spawn_set_version) DO UPDATE SET",
  "  source_content_manifest_hash = EXCLUDED.source_content_manifest_hash,",
  "  spawn_hash = EXCLUDED.spawn_hash,",
  "  model_version = EXCLUDED.model_version,",
  "  cluster_probability = EXCLUDED.cluster_probability,",
  "  world_width = EXCLUDED.world_width,",
  "  world_height = EXCLUDED.world_height,",
  "  movement_speed = EXCLUDED.movement_speed,",
  "  path_cell_size = EXCLUDED.path_cell_size,",
  "  winter_geometry = EXCLUDED.winter_geometry,",
  "  reachability_summary = EXCLUDED.reachability_summary;",
  "",
  "INSERT INTO public.game_content_spawns",
  "  (spawn_id, content_version, spawn_set_version, entity_type, kind, ordinal, active, biome, subzone, x, y)",
  valuesBlock(contentRows),
  "ON CONFLICT (spawn_id) DO UPDATE SET",
  "  content_version = EXCLUDED.content_version,",
  "  spawn_set_version = EXCLUDED.spawn_set_version,",
  "  entity_type = EXCLUDED.entity_type,",
  "  kind = EXCLUDED.kind,",
  "  ordinal = EXCLUDED.ordinal,",
  "  active = EXCLUDED.active,",
  "  biome = EXCLUDED.biome,",
  "  subzone = EXCLUDED.subzone,",
  "  x = EXCLUDED.x,",
  "  y = EXCLUDED.y;",
  "",
  "INSERT INTO public.game_world_nodes",
  "  (spawn_id, content_version, spawn_set_version, kind, cell, biome, subzone, x, y,",
  "   charges, max_charges, gather_s, respawn_s)",
  valuesBlock(nodeRows),
  "ON CONFLICT (spawn_id) DO UPDATE SET",
  "  content_version = EXCLUDED.content_version,",
  "  spawn_set_version = EXCLUDED.spawn_set_version,",
  "  kind = EXCLUDED.kind,",
  "  cell = EXCLUDED.cell,",
  "  biome = EXCLUDED.biome,",
  "  subzone = EXCLUDED.subzone,",
  "  x = EXCLUDED.x,",
  "  y = EXCLUDED.y,",
  "  charges = EXCLUDED.charges,",
  "  max_charges = EXCLUDED.max_charges,",
  "  gather_s = EXCLUDED.gather_s,",
  "  respawn_s = EXCLUDED.respawn_s,",
  "  respawn_at = NULL,",
  "  updated_at = now();",
  "",
  "INSERT INTO public.game_world_monsters",
  "  (spawn_id, content_version, spawn_set_version, kind, cell, biome, subzone, x, y, hp, max_hp, respawn_s)",
  valuesBlock(monsterRows),
  "ON CONFLICT (spawn_id) DO UPDATE SET",
  "  content_version = EXCLUDED.content_version,",
  "  spawn_set_version = EXCLUDED.spawn_set_version,",
  "  kind = EXCLUDED.kind,",
  "  cell = EXCLUDED.cell,",
  "  biome = EXCLUDED.biome,",
  "  subzone = EXCLUDED.subzone,",
  "  x = EXCLUDED.x,",
  "  y = EXCLUDED.y,",
  "  hp = EXCLUDED.hp,",
  "  max_hp = EXCLUDED.max_hp,",
  "  tagged_by = NULL,",
  "  tagged_at = NULL,",
  "  respawn_s = EXCLUDED.respawn_s,",
  "  respawn_at = NULL,",
  "  updated_at = now();",
  "",
  "DO $gate7_exit$",
  "BEGIN",
  `  IF (SELECT count(*) FROM public.game_content_spawns WHERE content_version = ${sqlText(manifest.content_version)}) <> ${manifest.spawns.length} THEN`,
  "    RAISE EXCEPTION 'Gate 7 canonical spawn set contains missing or unexpected rows';",
  "  END IF;",
  `  IF (SELECT count(*) FROM public.game_world_nodes WHERE content_version = ${sqlText(manifest.content_version)}) <> ${nodeRows.length} THEN`,
  "    RAISE EXCEPTION 'Gate 7 UUID node state is incomplete';",
  "  END IF;",
  `  IF (SELECT count(*) FROM public.game_world_monsters WHERE content_version = ${sqlText(manifest.content_version)}) <> ${monsterRows.length} THEN`,
  "    RAISE EXCEPTION 'Gate 7 UUID monster state is incomplete';",
  "  END IF;",
  "  IF EXISTS (SELECT 1 FROM public.game_world_nodes WHERE content_version = 'v2' AND kind = 'tungsten') THEN",
  "    RAISE EXCEPTION 'Gate 7 must retire all Tungsten nodes from v2';",
  "  END IF;",
  `  IF (SELECT count(*) FROM public.world_nodes WHERE kind = 'tungsten') <> ${legacyV1.tungsten_node_count} THEN`,
  `    RAISE EXCEPTION 'Gate 7 changed the historical v1 database Tungsten count of ${legacyV1.tungsten_node_count}';`,
  "  END IF;",
  `  IF (SELECT count(*) FROM public.world_nodes) <> ${legacyV1.node_count} OR (SELECT count(*) FROM public.world_monsters) <> ${legacyV1.monster_count} THEN`,
  `    RAISE EXCEPTION 'Gate 7 changed historical v1 database world counts (${legacyV1.node_count} nodes, ${legacyV1.monster_count} monsters)';`,
  "  END IF;",
  "  IF EXISTS (",
  "    SELECT 1 FROM public.game_content_spawns AS spawn",
  "    LEFT JOIN (",
  "      SELECT spawn_id, content_version, spawn_set_version, kind, cell, biome, subzone, x, y FROM public.game_world_nodes",
  "      UNION ALL",
  "      SELECT spawn_id, content_version, spawn_set_version, kind, cell, biome, subzone, x, y FROM public.game_world_monsters",
  "    ) AS state USING (spawn_id, content_version, spawn_set_version, kind, biome, subzone, x, y)",
  "    WHERE spawn.content_version = 'v2' AND state.spawn_id IS NULL",
  "  ) THEN",
  "    RAISE EXCEPTION 'Gate 7 canonical spawns and UUID state disagree';",
  "  END IF;",
  "  IF EXISTS (",
  "    SELECT 1 FROM public.game_world_nodes AS node",
  "    JOIN public.game_content_nodes AS definition",
  "      ON definition.content_version = node.content_version AND definition.kind = node.kind",
  "    WHERE node.biome = 'winter' AND NOT (",
  "      (definition.level_requirement BETWEEN 55 AND 79 AND node.subzone = 'lower_slopes')",
  "      OR (definition.level_requirement BETWEEN 80 AND 99 AND node.subzone = 'mid_mountain')",
  "      OR (definition.level_requirement BETWEEN 100 AND 119 AND node.subzone = 'upper_peaks')",
  "      OR (definition.level_requirement BETWEEN 120 AND 139 AND node.subzone = 'high_peaks')",
  "      OR (definition.level_requirement BETWEEN 140 AND 150 AND node.subzone = 'deepest_frontier')",
  "    )",
  "  ) THEN",
  "    RAISE EXCEPTION 'Gate 7 Winter node depth does not match source level';",
  "  END IF;",
  "  IF EXISTS (",
  "    SELECT 1 FROM public.game_world_monsters AS monster",
  "    JOIN public.game_content_monsters AS definition",
  "      ON definition.content_version = monster.content_version AND definition.kind = monster.kind",
  "    WHERE monster.biome = 'winter' AND NOT (",
  "      (definition.level_requirement BETWEEN 55 AND 79 AND monster.subzone = 'lower_slopes')",
  "      OR (definition.level_requirement BETWEEN 80 AND 99 AND monster.subzone = 'mid_mountain')",
  "      OR (definition.level_requirement BETWEEN 100 AND 119 AND monster.subzone = 'upper_peaks')",
  "      OR (definition.level_requirement BETWEEN 120 AND 139 AND monster.subzone = 'high_peaks')",
  "      OR (definition.level_requirement BETWEEN 140 AND 150 AND monster.subzone = 'deepest_frontier')",
  "    )",
  "  ) THEN",
  "    RAISE EXCEPTION 'Gate 7 Winter monster depth does not match source level';",
  "  END IF;",
  "  IF EXISTS (SELECT 1 FROM public.game_content_control) OR public.game_active_content_version() <> 'v1' THEN",
  "    RAISE EXCEPTION 'Gate 7 must leave v1 active by default';",
  "  END IF;",
  `  IF (SELECT spawn_hash FROM public.game_world_spawn_sets WHERE content_version = 'v2') <> ${sqlText(manifest.spawn_hash)} THEN`,
  "    RAISE EXCEPTION 'Gate 7 stored spawn hash drifted';",
  "  END IF;",
  "END",
  "$gate7_exit$;",
  "",
  "COMMIT;",
  "",
].join("\n");

if (checkOnly) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== generated) throw new Error("Gate 7 migration drifted; run node scripts/gate7/build-migration.mjs");
  console.log("Gate 7 migration is deterministic and current.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath.slice(root.length + 1)}`);
}
